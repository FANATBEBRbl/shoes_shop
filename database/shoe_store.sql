BEGIN;

CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role text NOT NULL,
    full_name text NOT NULL,
    login text NOT NULL UNIQUE,
    password text NOT NULL
);

CREATE TABLE product (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atricle text NOT NULL UNIQUE,
    name text NOT NULL,
    unit text NOT NULL,
    price numeric(12, 2) NOT NULL CHECK (price >= 0),
    provider text,
    manufacturer text,
    category text,
    discount integer DEFAULT 0 CHECK (discount BETWEEN 0 AND 100),
    stock_quantity integer NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    description text,
    photo text
);

CREATE TABLE pick_up (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location text NOT NULL
);

CREATE TABLE orders (
    order_number integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_date date NOT NULL,
    delivery_date date NOT NULL,
    pick_up_id integer REFERENCES pick_up (id),
    user_id integer REFERENCES users (id),
    client_code text,
    status text NOT NULL
);

CREATE TABLE orders_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id integer NOT NULL REFERENCES orders (order_number) ON DELETE CASCADE,
    product_id integer REFERENCES product (id),
    articul text NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0)
);

